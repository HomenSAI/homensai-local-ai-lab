"""Grade-11 chemistry (10 problems) with parameters drawn from a seeded RNG; correct answers are computed here, not typed.
Every task: (id, subject, topic, text, answer, rel_tol). The model must end with 'ОТВЕТ: <число>'."""
import math, random

TAIL = "\nРеши задачу. Покажи краткий ход решения. В последней строке напиши только: ОТВЕТ: <число> (без единиц измерения, десятичная точка или запятая)."


def mk():
    R = lambda i: random.Random(2000 + i)
    T = []

    def add(i, topic, text, ans, tol=0.02):
        T.append((f"c{i:02d}", "chem", topic, text + TAIL, float(ans), tol))

    r = R(1); m, w = r.choice([200, 250, 400, 500]), r.choice([5, 8, 10, 12, 15, 20])
    add(1, "массовая доля", f"Сколько граммов хлорида натрия содержится в {m} г раствора с массовой долей NaCl {w}%?", m * w / 100)
    r = R(2); n = r.choice([0.25, 0.5, 1.5, 2, 3])
    add(2, "количество вещества", f"Найдите массу (г) {n} моль серной кислоты H₂SO₄. Ar(H)=1, Ar(S)=32, Ar(O)=16.", n * 98)
    r = R(3); m = r.choice([50, 100, 150, 200])
    add(3, "газы, н.у.", f"Какой объём (л, н.у.) углекислого газа выделится при полном термическом разложении {m} г CaCO₃ (CaCO₃ → CaO + CO₂)? Ar(Ca)=40, Ar(C)=12, Ar(O)=16, Vm=22,4 л/моль.", m / 100 * 22.4)
    r = R(4); c = r.choice([0.005, 0.01, 0.05])
    add(4, "pH", f"Найдите pH раствора гидроксида бария Ba(OH)₂ с концентрацией {c} моль/л (диссоциация полная, при 25 °C, pH + pOH = 14). Ответ округлите до сотых.", 14 + math.log10(2 * c), 0.005)
    r = R(5); m, V = r.choice([4, 8, 10, 20]), r.choice([250, 500, 1000])
    add(5, "молярная концентрация", f"В {V} мл раствора растворено {m} г NaOH. Найдите молярную концентрацию (моль/л). Ar(Na)=23, Ar(O)=16, Ar(H)=1.", m / 40 / (V / 1000))
    r = R(6); a, b, ab = r.choice([0.1, 0.2, 0.4]), r.choice([0.1, 0.25, 0.5]), r.choice([0.2, 0.4, 0.6])
    add(6, "химическое равновесие", f"Для реакции A₂ + B₂ ⇌ 2AB равновесные концентрации (моль/л): [A₂] = {a}, [B₂] = {b}, [AB] = {ab}. Найдите константу равновесия Kc.", ab**2 / (a * b))
    r = R(7); m, q = r.choice([8, 16, 24, 32]), r.choice([890, 802, 1360])
    add(7, "термохимия", f"Термохимическое уравнение горения метана: CH₄ + 2O₂ = CO₂ + 2H₂O + {890} кДж. Сколько кДж теплоты выделится при сгорании {m} г метана? Ar(C)=12, Ar(H)=1.", m / 16 * 890)
    r = R(8); I, t = r.choice([2, 4, 5]), r.choice([1930, 3860, 9650])
    add(8, "электролиз", f"Через раствор сульфата меди(II) пропускают ток {I} А в течение {t} с. Найдите массу меди (г), выделившейся на катоде. Ar(Cu)=64, F=96500 Кл/моль, медь двухвалентна.", 64 * I * t / (2 * 96500))
    r = R(9); c1, v1, c2 = r.choice([0.1, 0.2, 0.5]), r.choice([20, 25, 50]), r.choice([0.1, 0.25, 0.4])
    add(9, "титрование", f"На нейтрализацию {v1} мл раствора HCl с концентрацией {c1} моль/л израсходовали раствор NaOH с концентрацией {c2} моль/л. Найдите объём раствора NaOH (мл).", c1 * v1 / c2)
    r = R(10); m, eta = r.choice([13, 26, 32.5, 65]), r.choice([80, 90, 75])
    add(10, "выход продукта", f"Цинк массой {m} г растворили в избытке соляной кислоты (Zn + 2HCl → ZnCl₂ + H₂). Выход водорода составил {eta}% от теоретического. Найдите практический объём H₂ (л, н.у.). Ar(Zn)=65, Vm=22,4 л/моль.", m / 65 * 22.4 * eta / 100)
    return T


TASKS = mk()

if __name__ == "__main__":
    for t in TASKS:
        print(t[0], t[2], round(t[4], 4))
