"""Write the measured maximum stable context into the llama-swap profiles.
Reads results_ctx.jsonl (bench_ctx.py) and config/llama-swap.yaml; writes config/llama-swap-ctx.yaml (candidate, NOT live).
Rules:
  * base profile  = largest stable context reachable with the KV cache in VRAM (fast), with its KV type;
  * <name>-MAXCTX = extra profile when the KV cache in system RAM (--no-kv-offload) reaches >= 1.5x that context;
  * vision profiles get half of the text context (the projector needs ~1 GB of VRAM);
  * flags other than --ctx-size / -ctk / -ctv / --no-kv-offload / --cache-ram stay exactly as they are.
usage: python gen_profiles_from_ctx.py [--cache-ram 4096]"""
import copy, json, os, re, shlex, sys
import yaml

AI = r"<PROJECT_DIR>"
SRC = os.path.join(AI, "config", "llama-swap.yaml")
DST = os.path.join(AI, "config", "llama-swap-ctx.yaml")
RES = os.path.join(AI, "bench_results", "results_ctx.jsonl")
CACHE_RAM = int(sys.argv[sys.argv.index("--cache-ram") + 1]) if "--cache-ram" in sys.argv else 4096

# bench model name -> gateway profile names that run the same weights
MAP = {
    "Qwen3.5-9B-MTP": ["Qwen3.5-9B-MTP-Q4_K_XL", "Qwen3.5-9B-MTP-Q4_K_XL-Vision"], "Qwen3.5-9B": ["Qwen3.5-9B-Q5_K_S", "Qwen3.5-9B-Q5_K_S-Draft"],
    "MiniCPM5-2B-Q8": ["MiniCPM5-2B-Q8_0"], "Spark-X2.5-4B-Q8": ["Spark-X2.5-4B-Q8_0"], "Bonsai-2-27B": ["Ternary-Bonsai-2-27B-PTQ1_0"],
    "Qwen3-VL-8B": ["Qwen3-VL-8B-Instruct-Q4_K_M"], "Qwen3-8B": ["Qwen3-8B-Draft"], "Gemma-3-12B": ["Gemma-3-12B-Draft"],
    "R1-Distill-Llama-8B": ["R1-Distill-Llama-8B-Draft"], "Qwen2.5-Coder-7B": ["Qwen2.5-Coder-7B-Draft"], "Llama-3.1-8B": ["Llama-3.1-8B-Draft"],
    "Gemma-4-12B": ["Gemma-4-12B-it"], "Gemma-4-12B-QAT": ["Gemma-4-12B-it-QAT"], "Gemma-4-E4B": ["Gemma-4-E4B-it"],
    "LFM2.5-2.6B": ["LFM2.5-2.6B"], "LFM2.5-8B-A1B": ["LFM2.5-8B-A1B"], "MiMo-9B": ["MiMo-V2.6-Distill-Qwen-9B-Draft"],
    "MiMo-9B-MTP": ["MiMo-V2.6-Distill-Qwen-9B-MTP"], "Ornith-1.5-9B": ["Ornith-1.5-9B-MTP", "Ornith-1.5-9B-DFlash"],
    "Mistral-Nemo-12B": ["Mistral-Nemo-12B"], "Qwen2.5-VL-7B": ["Qwen2.5-VL-7B"],
}


def edit_cmd(cmd, ctx, kv, nkvo):
    t = shlex.split(cmd.replace("\n", " "))
    out, i = [], 0
    while i < len(t):
        a = t[i]
        if a in ("--ctx-size", "-c", "-ctk", "--cache-type-k", "-ctv", "--cache-type-v", "--cache-ram"): i += 2; continue
        if a == "--no-kv-offload": i += 1; continue
        out.append(a); i += 1
    out += ["--ctx-size", str(ctx), "--cache-ram", str(CACHE_RAM), "-ctk", kv, "-ctv", kv] + (["--no-kv-offload"] if nkvo else [])
    return " ".join(shlex.quote(x) if re.search(r"[^\w@%+=:,./${}-]", x) else x for x in out)


def main():
    cfg = yaml.safe_load(open(SRC, encoding="utf-8")); new = copy.deepcopy(cfg); rows = []
    for l in open(RES, encoding="utf-8"):
        r = json.loads(l)
        if "cfgs" not in r or r["model"] not in MAP: continue
        gpu = {k: v for k, v in r["cfgs"].items() if k.startswith("gpu") and v["best_ctx"]}
        ram = r["cfgs"].get("ram-q8", {"best_ctx": 0})
        if not gpu and not ram["best_ctx"]: continue
        gk = max(gpu, key=lambda k: (gpu[k]["best_ctx"], -["gpu-f16", "gpu-q8", "gpu-q4"].index(k))) if gpu else None
        base_ctx = gpu[gk]["best_ctx"] if gk else 0
        for prof in MAP[r["model"]]:
            if prof not in cfg["models"]: continue
            kvname = {"gpu-f16": "f16", "gpu-q8": "q8_0", "gpu-q4": "q4_0"}.get(gk, "q8_0")
            vision = "Vision" in prof or "VL" in prof
            if gk:
                ctx = base_ctx // 2 // 4096 * 4096 if vision else base_ctx
                new["models"][prof]["cmd"] = edit_cmd(cfg["models"][prof]["cmd"], ctx, kvname, False)
                rows.append((prof, ctx, gk, gpu[gk]["tg"]))
            if ram["best_ctx"] and ram["best_ctx"] >= 1.5 * max(base_ctx, 1) and not vision:
                extra = prof + "-MAXCTX"; new["models"][extra] = copy.deepcopy(cfg["models"][prof])
                new["models"][extra]["name"] = extra
                new["models"][extra]["cmd"] = edit_cmd(cfg["models"][prof]["cmd"], ram["best_ctx"], "q8_0", True).replace(f"--alias {prof}", f"--alias {extra}")
                new["routing"]["router"]["settings"]["groups"]["all-local-llm"]["members"].append(extra)
                rows.append((extra, ram["best_ctx"], "ram-q8", ram["tg"]))
    head = ("# llama-swap profiles with the MEASURED maximum stable context (bench_ctx.py: 3-needle recall at ~80% fill, VRAM and RAM guards).\n"
            "# Generated by bench_results/gen_profiles_from_ctx.py from config/llama-swap.yaml. Candidate file: not live until copied over llama-swap.yaml.\n")
    open(DST, "w", encoding="utf-8").write(head + yaml.safe_dump(new, sort_keys=False, allow_unicode=True, width=100000))
    print(f"profiles updated: {len(rows)}")
    for p, c, k, tg in rows: print(f"  {p:42s} ctx {c:>7d}  {k:8s} tg {tg}")


if __name__ == "__main__":
    main()
